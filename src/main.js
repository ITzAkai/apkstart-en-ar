// ---------------- Core actions ----------------

let installBusy = null;   // path being installed: repeated double-clicks on an APK arrive via second-instance, and installs must not run concurrently
let lastInstallErr = { msg: '', at: 0 };

async function runInstall(filePath) {
  showWindow();
  // The same package is already installing (icon clicked / file dragged several times) -> say so once, don't run the install again
  if (installBusy) {
    if (installBusy === filePath) {
      send('toast', { type: 'info', message: t('This APK is already being installed, please wait…') });
      return { ok: false, error: t('Already installing') };
    }
    send('toast', { type: 'info', message: t('Another install is in progress. Please wait for it to finish.') });
    return { ok: false, error: t('Another install is in progress') };
  }
  installBusy = filePath;
  send('install:start', { file: filePath });
  try {
    const result = await installer.install(filePath, (p) => send('install:progress', p));
    send('install:done', result);
    // Make Explorer refresh the new desktop icon right away, otherwise users think "no shortcut was created"
    windowctl.refreshShell().catch(() => {});
    const name = result.app.label;
    notify(t('Install complete'), result.app.shortcutPath
      ? t('{name} installed, desktop shortcut created', { name })
      : t('{name} installed', { name }));
    return result;
  } catch (e) {
    send('install:error', { message: e.message, file: filePath });
    if (e.needsSetup) send('ui:navigate', 'setup');
    // Show the same error as a system notification at most once per 8 s, so retries don't flood the screen corner
    const now = Date.now();
    if (e.message !== lastInstallErr.msg || now - lastInstallErr.at > 8000) {
      lastInstallErr = { msg: e.message, at: now };
      // When the window is in front the user already sees the message in the UI; no system notification needed
      if (!mainWindow || !mainWindow.isVisible() || mainWindow.isMinimized()) {
        notify(t('Install failed'), e.message.slice(0, 120));
      }
    }
    throw e;
  } finally {
    installBusy = null;
  }
}

/**
 * Download and install a new version, then the update-apply script takes over "replace + restart".
 * Shared by the UI and the tray menu.
 */
async function runUpdate() {
  if (updateBusy) return { ok: false, error: t('An update is already in progress') };
  updateBusy = true;
  const sendProgress = (p) => send('update:progress', p);
  try {
    const info = updateInfo && updateInfo.hasUpdate ? updateInfo : await updater.check();
    updateInfo = info;
    if (!info.hasUpdate) return { ok: false, error: info.disabled ? info.message : t('Already up to date') };
    if (!info.asset) {
      const page = info.htmlUrl || Updater.repoUrl();
      if (page) shell.openExternal(page).catch(() => {});
      return { ok: false, error: t('This release has no package that can be installed directly; the GitHub release page was opened'), manual: true };
    }
    sendProgress({ stage: 'download', percent: 0, message: t('Preparing download…') });
    const job = await updater.prepare(info);
    sendProgress({ stage: 'apply', percent: 100, message: t('Replacing the app and restarting…') });
    updater.apply(job);
    // Give the UI a moment to show "restarting", then quit normally (before-quit tucks the emulator window away)
    setTimeout(() => { quitting = true; app.quit(); }, 900);
    return { ok: true, version: info.version, mode: job.mode };
  } catch (e) {
    sendProgress({ stage: 'error', percent: 0, message: e.message });
    return { ok: false, error: e.message };
  } finally {
    updateBusy = false;
  }
}

async function runLaunch(pkg) {
  const t0 = Date.now();
  const mark = (s) => appLog(`launch ${pkg} ${s} +${Date.now() - t0}ms`);
  appLog(`launch start ${pkg}`);
  try {
    // 1) Open the app window with the startup animation first: the user never sees the Android home screen or the emulator window
    openAppWindow(pkg, t('Starting the Android runtime…'));
    // During boot hide the emulator main window and the qemu / netsimd black console windows so nothing flashes.
    // Suppression is permanent (after embedding it automatically skips the embedded window, see appwin.embed).
    // Must await here: continuing before suppression is active lets the black window show at startup.
    if (winAgent) { try { await armAgent(winAgent); } catch (_) { /* ignore */ } }
    if (mainWindow && mainWindow.isVisible() && !IS_DEV) mainWindow.hide();

    const r = await installer.launch(pkg, {
      onLog: (m) => { send('runtime:log', m); appLog(`  rt ${m}`); },
      onMark: mark,
      beforeStart: async (rt) => {
        mark('engine ready');
        appWin.setState({ tip: t('Opening the app…') });
        // Immersive mode + animations off + dismiss lock screen: done once, then every launch is instant
        await rt.client.prepareForeground().catch(() => {});
        mark('foreground ready');
      },
    });
    mark('app started');

    // 2) Only embed the image into the window once the app is really alive (otherwise the user sees a flash of the home screen / crash page)
    const embedded = await appWin.embed();
    if (!embedded) appLog(`embed failed: ${appWin.lastEmbedError || 'unknown'}`);
    mark(`embedded=${embedded}`);
    // After embedding, raise the window above others. Otherwise windows on top (browsers etc.) cover the Android image,
    // the user sees "black screen / image not filling", and clicks never reach the app (eaten by the window on top).
    // Briefly set topmost and undo it right away: borrow topmost once to raise the Z order without staying on top.
    if (appWin.isOpen) {
      try {
        appWin.win.show();
        appWin.win.setAlwaysOnTop(true);
        appWin.win.moveTop();
        appWin.win.focus();
        setTimeout(() => {
          if (appWin.isOpen) {
            try { appWin.win.setAlwaysOnTop(false); } catch (_) { /* window already closed */ }
          }
        }, 700);
      } catch (_) { /* window may have just closed */ }
    }
    appWin.setState({ ready: true, tip: '' });
    // If embedding failed (emulator window not created yet), retry twice: the user sees a black window
    // that recovers once a background retry succeeds, without having to reopen it.
    if (!embedded) {
      setTimeout(() => { if (appWin.isOpen) appWin.embed().catch(() => {}); }, 1500);
      setTimeout(() => { if (appWin.isOpen) appWin.embed().catch(() => {}); }, 4000);
    }
    // Container session: the environment is ready, so only "trim per app + start background polling" here;
    // Android isn't booted again for this app. The mouse mapping hook is set by the window focus event
    // according to settings, and removed on blur.
    deviceSize.value = null;
    appWin.refreshPointer();
    await runtime.beginApp(pkg, { onActive: onContainerActive }).catch(() => {});
    // Game / low-latency mode: the window agent scans less often, reducing system-wide stutter from desktop-wide EnumWindows
    if (winAgent) {
      const game = store.getSettings().engine?.priorityMode === 'game';
      winAgent.setPerformanceMode(game).catch(() => {});
    }
    send('app:launched', { package: pkg, engine: r.engine });
    appLog(`launch ok ${pkg} embedded=${embedded}`);
    return { ok: true, embedded };
  } catch (e) {
    appLog(`launch failed ${pkg}: ${e && (e.stack || e.message)}`);
    try { appWin.close({ keepApp: true }); } catch (_) { /* ignore */ }
    // On launch failure keep the emulator window suppressed too (don't let it show up as a standalone emulator window);
    // the next app click still goes through the same hide -> embed path.
    if (winAgent) armAgent(winAgent).catch(() => {});
    showWindow();
    send('toast', { type: 'error', message: t('Launch failed: {error}', { error: e.message }) });
    return { ok: false, error: e.message };
  }
}

/**
 * Background tasks on/off depending on whether the container has app windows.
 * File sync walks the shared folder every 8 s with an adb find/stat, and the notification bridge polls too;
 * these used to start unconditionally with ApkStart, even with no Android app open.
 * Now they run only while the container really has apps, and stop as soon as the last window closes.
 */
function onContainerActive(on) {
  if (on) {
    sharer?.start(8000);
    startNotifier();
  } else {
    sharer?.stop();
    notifier?.stop();
  }
}

/** Notification bridge: polls only while an app window is open and stops when it closes, to avoid idling */
function startNotifier() {
  if (!notifier) {
    notifier = new NotifyBridge({
      getClient: () => runtime.client(),
      getAppLabel: (pkg) => (store.getApp(pkg) || {}).label || pkg,
      getAppIcon: (pkg) => (store.getApp(pkg) || {}).icoPath || '',
      onOpen: (pkg) => {
        if (appWin && appWin.isOpen && appWin.pkg === pkg) {
          appWin.win.show();
          appWin.win.focus();
        } else {
          runLaunch(pkg).catch(() => {});
        }
      },
    });
  }
  notifier.start();
}

