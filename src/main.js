/** Creates the tray on the first call; later calls (e.g. after a language change) only refresh its tooltip and menu. */
function buildTray() {
  if (!tray) {
    try {
      tray = new Tray(loadBrandIcon(16));
    } catch (_) {
      return;
    }
    // Windows convention: a single click on the tray icon opens the main window (double click works too).
    // With only double-click bound, users thought the tray icon was broken.
    // The menu opens on right click, so showWindow on a single click doesn't conflict with it.
    tray.on('click', () => showWindow());
    tray.on('double-click', () => showWindow());
    setInterval(refreshTrayMenu, 5000).unref?.();
  }
  tray.setToolTip(t('ApkStart — Android app runner'));
  refreshTrayMenu();
}

