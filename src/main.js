/**
 * Rotation = swap the physical panel size and restart the emulator.
 *
 * This is the only way to get an upright, full-size landscape view (all three wrong paths were tried):
 *   - wm size: only changes the logical resolution; the physical LCD stays portrait -> the image lies sideways in a strip at the top left;
 *   - wm density: framebuffer size unchanged -> the image doesn't fill; maximized, a large blank area remains on the right;
 *   - adb emu rotate: only rotates the content; the system is still in portrait.
 * Only swapping hw.lcd.width/height to landscape and restarting makes Qt open a landscape window with an upright, full image.
 */
async function restartForOrientation(landscape) {
  if (!appWin || !appWin.isOpen) return false;
  const pkg = appWin.pkg;
  store.saveSettings({ display: { landscape: !!landscape } });
  send('runtime:log', landscape ? t('Switching to landscape: restarting the Android runtime…') : t('Switching back to portrait: restarting the Android runtime…'));
  try {
    // Detach the embedded window first so no black window is left on the desktop during the restart
    try { await appWin.agent.detach(); } catch (_) { /* ignore */ }
    await runtime.stop({ graceful: false }).catch(() => {});
    appLog(`rotate -> landscape=${landscape} restarting runtime`);
    const rt = await runtime.ensure({
      onLog: (m) => { send('runtime:log', m); appLog(`  rt ${m}`); },
    });
    if (!rt || !rt.ok) return false;
    await runtime.waitForNetwork({ onLog: () => {}, timeoutMs: 25000 }).catch(() => null);
    if (pkg) {
      const app = store.getApp(pkg);
      if (app) {
        await rt.client.install(app.apkPath).catch(() => {});
        await rt.client.startApp(app.package, app.activity, {}).catch(() => {});
      }
    }
    await new Promise((r) => setTimeout(r, 1500));
    const embedded = await appWin.embed().catch(() => false);
    if (!embedded) {
      setTimeout(() => { if (appWin.isOpen) appWin.embed().catch(() => {}); }, 1500);
      setTimeout(() => { if (appWin.isOpen) appWin.embed().catch(() => {}); }, 4000);
    }
    appWin.scheduleFit(6);
    return true;
  } catch (e) {
    appLog(`rotate restart failed: ${e && e.message}`);
    return false;
  }
}

/** Open (or reuse) the "one clean window per app" */
function openAppWindow(pkg, tip) {
  const rec = store.getApp(pkg);
  const land = !!displaySettings().landscape;
  const p0 = portraitSize();
  appWin.open({
    pkg,
    label: (rec && rec.label) || pkg,
    iconPath: rec && rec.icoPath,
    // In landscape open the window with a landscape ratio, otherwise a landscape image in a portrait window leaves big black bars
    portrait: land ? { w: p0.h, h: p0.w } : p0,
    fullscreen: displaySettings().mode === 'fullscreen',
  });
  appWin.setIcon(rec && rec.icoPath);
  // Initialize with the saved orientation on open (the physical panel orientation is decided in doctor.lcdFor)
  appWin.setState({
    tip: tip || t('Starting the Android runtime…'),
    ready: false,
    landscape: !!displaySettings().landscape,
  });
  currentAppPkg = pkg;
}

async function toggleDisplayMode() {
  const next = store.saveSettings({
    display: { mode: displaySettings().mode === 'fullscreen' ? 'window' : 'fullscreen' },
  });
  const full = next.display.mode === 'fullscreen';
  if (appWin && appWin.isOpen) {
    if (full) appWin.win.maximize();
    else appWin.win.unmaximize();
    appWin.scheduleFit(6);
    // Full screen = landscape: change the physical panel and restart the runtime, otherwise the portrait image just gets bigger with a blank area on the right
    if (!!displaySettings().landscape !== full) {
      appWin.rotate(restartForOrientation).catch(() => {});
    }
  }
  return next.display.mode;
}

/** On first run install adb / emulator / system image in one go, no separate steps 1-5 */
let deploying = false;
async function autoDeploy({ force = false } = {}) {
  if (deploying || !store.getSettings().autoDeploy) return { ok: false, error: 'skipped' };
  // Download-failure cooldown: previously, as long as checkEnv() still reported missing components, every ApkStart
  // start re-downloaded the 1.5 GB runtime package and the user saw "it keeps downloading".
  // After a failure a timestamp is stored and automatic retries pause for 30 minutes; when the user clicks "one-click deploy"
  // force=true retries immediately. Success or a forced run clears the cooldown.
  const COOLDOWN_MS = 30 * 60 * 1000;
  const lastFail = Number(store.getSettings().runtime.deployFailedAt || 0);
  if (!force && lastFail && Date.now() - lastFail < COOLDOWN_MS) {
    appLog(`autoDeploy cooling down (last failure at ${new Date(lastFail).toISOString()}), skipping automatic retry`);
    return { ok: false, error: 'cooldown', cooldown: true, until: lastFail + COOLDOWN_MS };
  }
  deploying = true;
  const progress = (p) => send('provision:progress', { ...p, component: p.component || 'all' });
  let succeeded = false;
  try {
    const env = await runtime.provisioner.checkEnv();
    const needEngine = !env.emulator.ok || !env.sysimg.ok;
    // The lite edition prefers "this project's runtime pack on GitHub": one file with emulator + system image,
    // with downloads and updates both coming from GitHub.
    // If the pack is unavailable (offline / asset not published yet / rate limited), install each part from the official source.
    const packSource = require('./core/sources').updateRepo() || store.getSettings().runtime.runtimePackUrl;
    if (needEngine && packSource && store.getSettings().runtime.preferGithubRuntime !== false) {
      try {
        progress({ message: t('Downloading the runtime from GitHub…') });
        await runtime.provisioner.installRuntimePack(progress);
        const afterPack = await runtime.provisioner.checkEnv();
        if (afterPack.emulator.ok && afterPack.sysimg.ok) {
          succeeded = true;
          return { ok: true, source: 'github' };
        }
        progress({ message: t('The runtime package is incomplete; completing it from the official source…') });
      } catch (e) {
        progress({ message: t('GitHub runtime unavailable ({error}); using the official source…', { error: e.message }) });
      }
    }
    if (!env.adb.ok) {
      progress({ message: t('Preparing adb…') });
      await runtime.provisioner.installAdb(progress);
    }
    if (!env.emulator.ok) {
      progress({ message: t('Preparing the Android runtime…') });
      await runtime.provisioner.installEmulator(progress);
    }
    if (!env.sysimg.ok) {
      progress({ message: t('Preparing the Android system image…') });
      await runtime.provisioner.installSystemImage(progress);
    }
    const after = await runtime.provisioner.checkEnv();
    succeeded = !!(after.adb.ok && after.emulator.ok && after.sysimg.ok);
    return { ok: succeeded };
  } catch (e) {
    return { ok: false, error: e.message };
  } finally {
    // Only a real failure starts the cooldown; a successful deploy clears the old failure record.
    try {
      store.saveSettings({ runtime: { deployFailedAt: succeeded ? 0 : Date.now() } });
    } catch (_) { /* failing to save settings doesn't change this result */ }
    deploying = false;
  }
}

