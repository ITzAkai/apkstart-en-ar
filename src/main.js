  ipcMain.handle('runtime:setDataSize', async (_e, gb) => {
    const want = Math.max(0, Math.min(64, Number(gb) || 0));
    store.saveSettings({ engine: { dataPartitionGB: want } });
    if (!want) {
      const info = runtime.emulator.dataInfo();
      return { ok: true, auto: true, ...info };
    }
    const mb = Math.round(want * 1024);
    // The image can't be changed while qemu holds it, so stop the container first (apps exit too, as expected)
    let stopped = false;
    try {
      const online = await runtime.client().isOnline().catch(() => false);
      if (runtime.emulator.running() || online) {
        await runtime.stop().catch(() => {});
        stopped = true;
      }
    } catch (_) { /* ignore */ }
    try {
      const r = runtime.emulator.resizeDataPartition(mb);
      appLog(`data partition -> ${want}GB: ${JSON.stringify(r)}`);
      if (r && r.ok) {
        notify(t('Data partition resized'), stopped
          ? t('Android now has about {gb} GB of space (runtime restarted)', { gb: want })
          : t('Android now has about {gb} GB of space', { gb: want }));
      }
      return { ok: !!(r && r.ok), stopped, ...r, ...runtime.emulator.dataInfo() };
    } catch (e) {
      return { ok: false, error: e.message };
    }
  });

  ipcMain.handle('runtime:cleanup', async (_e, opts = {}) => {
    // Explicit two-step confirmation: list first, delete only after the user confirms; only ApkStart's own runtime folder is cleaned
    const pass = { apply: false, aggressive: !!opts.aggressive, includeSnapshots: !!opts.includeSnapshots };
    if (!opts.apply) return runtime.cleanup(pass);
    const preview = await runtime.cleanup(pass);
    const { response } = await dialog.showMessageBox(mainWindow, {
      type: 'warning',
      buttons: [t('Cancel'), t('Clean up {n} items', { n: preview.candidates.length })],
      defaultId: 0,
      cancelId: 0,
      title: t('Confirm runtime cache cleanup'),
      message: t('About {mb} MB will be freed', { mb: (preview.candidates.reduce((n, c) => n + c.size, 0) / 1048576).toFixed(0) }),
      detail: `${opts.includeSnapshots
        ? t('The runtime is stopped first, then old images, quick-boot snapshots of the current AVD, lock files and caches of inactive AVDs are deleted. Installed apps are kept (only snapshots are cleared).')
        : t('Only old images, old snapshots, lock files and caches of inactive AVDs are deleted; installed apps are kept.')
      } ${t('This cannot be undone. Consider exporting a diagnostics report first.')}`,
    });
    if (response !== 1) return { ...preview, cancelled: true };
    return runtime.cleanup({ apply: true, aggressive: !!opts.aggressive, includeSnapshots: !!opts.includeSnapshots });
  });

  // Full Android data reset: wipe the /data user partition + installed apps + quick-boot snapshots,
  // returning the AVD to a clean "freshly installed" state. Really deletes several GB, so the UI must confirm twice.
