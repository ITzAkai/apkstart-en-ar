/**
 * Full edition (bundled runtime) takes over automatically:
 * the release ships runtime/ (emulator + platform-tools + AEHD + ARM compat image) next to ApkStart.exe.
 * On first start (no settings.json yet) runtime.dir is pointed at it and compat mode is enabled,
 * so it works out of the box with no downloads or setup. Users can still switch back to the online edition in Settings.
 */
function bootstrapBundledRuntime() {
  try {
    const exeDir = path.dirname(process.execPath);
    // The portable build keeps the runtime next to the exe; electron-builder's portable unpacks resources
    // into resources/, alongside the process exe, so check several candidate locations.
    const candidates = [
      path.join(exeDir, 'runtime'),
      path.join(path.dirname(exeDir), 'runtime'),
      path.join(process.resourcesPath || '', 'runtime'),
      path.join(process.resourcesPath || '', 'app', 'runtime'),
    ];
    // A bundled runtime only needs "emulator + any complete system image"; the API level is not hardcoded:
    // the single-file release may ship a smaller AOSP image, and hardcoding API34 would make it look missing.
    const hasImage = (dir) => {
      const root = path.join(dir, 'system-images');
      let apis = [];
      try { apis = fs.readdirSync(root); } catch (_) { return false; }
      for (const api of apis) {
        let tags = [];
        try { tags = fs.readdirSync(path.join(root, api)); } catch (_) { continue; }
        for (const tag of tags) {
          let abis = [];
          try { abis = fs.readdirSync(path.join(root, api, tag)); } catch (_) { continue; }
          for (const abi of abis) {
            const d = path.join(root, api, tag, abi);
            // In the single-file release images are stored compressed (system.img.xz / .gz) and unpacked on first start.
            // Accepting only system.img would treat a bundled image as missing and start a download instead.
            const hasSys = ['system.img', 'system.img.xz', 'system.img.gz']
              .some((f) => fs.existsSync(path.join(d, f)));
            if (hasSys && fs.existsSync(path.join(d, 'kernel-ranchu'))) return true;
          }
        }
      }
      return false;
    };
    const bundled = candidates.find((dir) =>
      fs.existsSync(path.join(dir, 'emulator', 'emulator.exe')) && hasImage(dir));
    if (!bundled) return;

    const s = store.getSettings();
    // Old versions only took over when settings.json didn't exist: users who installed the online edition first and then
    // unpacked the full edition were stuck in the "missing components" wizard. Now take over whenever the current runtime dir has no emulator.
    const explicit = String(s.runtime.dir || '').trim();
    const current = explicit || path.join(store.DATA_DIR, 'runtime');
    const currentExe = path.join(current, 'emulator', 'emulator.exe');
    // After the portable build is moved/upgraded (unpacked to a new folder), settings still hold the old path:
    // only trust "the runtime under this exe's folder", otherwise the old package's components stay in use
    // (seen in practice: the old emulator lacked emulator-check -> accel probe failed -> fell back to TCG software emulation).
    const sameTree = path.resolve(current).toLowerCase()
      .startsWith(path.resolve(exeDir).toLowerCase());
    const currentOk = fs.existsSync(currentExe) && sameTree;
    // A folder the user picked (outside the exe tree, e.g. D:\ApkStartRuntime or another drive)
    // is always respected: they may want to save space on C: or share one runtime between several portable builds.
    // Old versions unconditionally overwrote it with the bundled runtime next to the exe, so
    // "I changed the runtime data folder in Settings but it still downloads to the old folder / AppData" (issue #23).
    if (explicit && !sameTree && fs.existsSync(currentExe)) {
      if (s.engine.gpuMode === 'swiftshader_indirect' || s.engine.memoryMB === 4096) {
        store.saveSettings({ engine: { gpuMode: 'auto', autoMemory: true, memoryMB: 0, cores: 0 } });
      }
      return;
    }
    // An existing working runtime (including the online edition) is respected: the AVD user data lives there and must not be moved silently
    if (currentOk) {
      // But still turn on auto settings; hardcoded 4G / 4 cores / deprecated GPU modes from old configs must not be kept
      if (s.engine.gpuMode === 'swiftshader_indirect' || s.engine.memoryMB === 4096) {
        store.saveSettings({ engine: { gpuMode: 'auto', autoMemory: true, memoryMB: 0, cores: 0 } });
      }
      return;
    }
    // Compat mode only when the bundled image is a Google Play image; AOSP images carry native x86_64 libraries
    let playBundled = false;
    try {
      const root = path.join(bundled, 'system-images');
      for (const api of fs.readdirSync(root)) {
        for (const tag of fs.readdirSync(path.join(root, api))) {
          if (/playstore|google_apis/i.test(tag)) playBundled = true;
        }
      }
    } catch (_) { /* ignore */ }
    store.saveSettings({
      runtime: { dir: bundled, compatImage: playBundled },
      engine: { gpuMode: 'auto', autoMemory: true },
    });
  } catch (_) { /* takeover failure doesn't block startup; the online setup takes over */ }
}
